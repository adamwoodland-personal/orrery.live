const COLOUR = { O: 'blue-white', B: 'blue-white', A: 'white', F: 'yellow-white', G: 'yellow', K: 'orange', M: 'red' };
const KIND = { '0': 'hypergiant', 'Ia+': 'hypergiant', 'Ia0': 'hypergiant', Iab: 'supergiant', Ia: 'supergiant', Ib: 'supergiant', I: 'supergiant', II: 'bright giant', III: 'giant', IV: 'subgiant', VI: 'subdwarf', V: 'main-sequence star' };
const PREFIX = { sd: 'VI', d: 'V', g: 'III', c: 'I' };

// "a blue-white giant", "an orange main-sequence star with a companion", "a carbon star"; '' if unknown.
function typePhrase(spect) {
	if (!spect) return '';
	// "A0V+B9" and "K0III + A5V" have a companion; the "+" in "K2+IIb" is part of the class.
	const companion = /\+\s*[OBAFGKMWDCS]/.test(spect) ? ' with a companion' : '';
	let p = spect.split(/\s*\+\s*(?=[OBAFGKMWDCS?.])/)[0].trim().replace(/^k[OBAFGKM][\d.]*h([OBAFGKM][\d.]*)m[OBAFGKM][\d.]*/, '$1');
	let words;
	if (/^W[CNOR]/.test(p)) words = 'hot Wolf-Rayet star';
	else if (/^D[ABCOQXZ]?(\d|$|[^a-z])/.test(p)) words = 'white dwarf';
	else if (/^(C|R\d|N\d)/.test(p)) words = 'carbon star';
	else if (/^S(\d|$|[^a-z])/.test(p)) words = 'S-type red giant';
	else {
		let lum = null;
		const pre = p.match(/^(sd|d|g|c)(?=[OBAFGKM])/);
		if (pre) { lum = PREFIX[pre[1]]; p = p.slice(pre[1].length); }
		const colour = COLOUR[p[0]];
		if (!colour) return '';
		const rest = p.replace(/^[OBAFGKM][\d.]*(?:[-/][OBAFGKM]?[\d.]+)*/, '');
		const m = rest.match(/^[\s:+]*(Ia\+|Ia0|0|Iab|Ia|Ib|III|II|IV|VI|V|I)/);   // ':' marks an uncertain class ("K2:III:")
		if (m) lum = m[1];
		words = colour + ' ' + (lum ? KIND[lum] : 'star');
	}
	return (/^[aeiou]|^S-/i.test(words) ? 'an ' : 'a ') + words + companion;
}

function lightYears(ly) {
	const s = ly < 10 ? ly.toFixed(1) : String(Math.round(ly));
	return s.replace(/\B(?=(\d{3})+(?!\d))/g, ',') + ' light-year' + (ly === 1 ? '' : 's');
}

export function starSentence(index) {
	const e = STAR_INFO[index];
	if (!e) return 'A star with no catalogued type or distance here.';
	const [dist, spect, , , note] = e;
	if (note) return note;
	const t = typePhrase(spect);
	const cap = (s) => s[0].toUpperCase() + s.slice(1);
	if (t && dist != null) return cap(t) + (t.includes(' with ') ? ', about ' : ' about ') + lightYears(dist) + ' away.';
	if (t) return cap(t) + ' whose distance is not well measured.';
	if (dist != null) return 'A star about ' + lightYears(dist) + ' away.';
	return 'A star whose type and distance are not well measured.';
}

