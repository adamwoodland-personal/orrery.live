// IAU 1976 (Lieske) precession angles from J2000.0 to B1875.0 = JD 2405889.258550475.
const T = (2405889.258550475 - 2451545) / 36525;
const ZETA = (2306.2181 * T + 0.30188 * T * T + 0.017998 * T * T * T) / 3600 * D2R;
const Z = (2306.2181 * T + 1.09468 * T * T + 0.018203 * T * T * T) / 3600 * D2R;
const THETA = (2004.3109 * T - 0.42665 * T * T - 0.041833 * T * T * T) / 3600 * D2R;
const COS_T = Math.cos(THETA), SIN_T = Math.sin(THETA);

/** Full IAU name of the constellation containing J2000 position (ra, dec) in degrees; '' for bad input. */
export function constellationAt(ra, dec) {
	ra = Number(ra);
	dec = Number(dec);
	if (!Number.isFinite(ra) || !Number.isFinite(dec)) return '';
	dec = Math.max(-90, Math.min(90, dec)) * D2R;
	const a = ra * D2R + ZETA, cd = Math.cos(dec), sd = Math.sin(dec);
	const x = COS_T * cd * Math.cos(a) - SIN_T * sd, y = cd * Math.sin(a);
	const z = SIN_T * cd * Math.cos(a) + COS_T * sd;
	const d = Math.atan2(z, Math.hypot(x, y)) / D2R; // B1875 declination, degrees
	let h = (Math.atan2(y, x) + Z) / D2R / 15; // B1875 right ascension, hours
	h = ((h % 24) + 24) % 24;
	for (let i = 0; i < ROMAN.length; i += 4) {
		if (d >= ROMAN[i + 2] && h >= ROMAN[i] && h < ROMAN[i + 1]) return IAU[ROMAN[i + 3]][1];
	}
	return 'Octans'; // not reached: the last row covers everything south of -90
}
